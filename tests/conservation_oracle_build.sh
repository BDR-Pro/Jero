#!/bin/sh
# Standalone build for the RingCT conservation oracle (see conservation_oracle.md).
#
# Compiles the REAL consensus verifiers directly from this repository's
# sources, without a configured cmake build tree, and without dev packages
# for libunbound (DNS code is stubbed; see conservation_oracle_stubs.cpp).
#
# Requirements: g++, libssl-dev, boost headers, libsodium (runtime library is
# enough - the few missing headers are shimmed into $OUT/shim below).
# Tested on Ubuntu x86_64 / WSL.
#
# Usage:
#   tests/conservation_oracle_build.sh          # builds into ./build-oracle
#   OUT=/tmp/o tests/conservation_oracle_build.sh
#   ./build-oracle/conservation_oracle          # full battery (~10 min)
#   ./build-oracle/conservation_oracle_probes offsets
#   ./build-oracle/conservation_oracle_probes emission
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=${OUT:-$ROOT/build-oracle}
mkdir -p "$OUT/obj" "$OUT/shim/sodium" "$OUT/shim/crypto/wallet"

# --- headers normally provided by libsodium-dev or generated by cmake ------
SHIM=$OUT/shim/sodium/crypto_shorthash_siphash24.h
if [ ! -f "$SHIM" ]; then
  cat > "$SHIM" <<'EOF'
#ifndef crypto_shorthash_siphash24_H
#define crypto_shorthash_siphash24_H
#include <stddef.h>
#ifdef __cplusplus
extern "C" {
#endif
#define crypto_shorthash_siphash24_BYTES 8U
#define crypto_shorthash_siphash24_KEYBYTES 16U
int crypto_shorthash_siphash24(unsigned char *out, const unsigned char *in,
    unsigned long long inlen, const unsigned char *k);
#ifdef __cplusplus
}
#endif
#endif
EOF
fi

if [ ! -f "$OUT/shim/export.h" ]; then
  cat > "$OUT/shim/export.h" <<'EOF'
#ifndef export_shim_H
#define export_shim_H
#define SODIUM_EXPORT
#define SODIUM_EXPORT_WEAK
#endif
EOF
fi

# crypto/wallet/ops.h is generated from empty.h.in by cmake when the internal
# "cn" wallet crypto is selected; reproduce it so the internal crypto is used.
cp -f "$ROOT/src/crypto/wallet/empty.h.in" "$OUT/shim/crypto/wallet/ops.h"

CPP="g++ -c -std=c++17 -O2 -DNDEBUG -DAUTO_INITIALIZE_EASYLOGGINGPP -w"
CC="gcc -c -std=gnu11 -O2 -DNDEBUG -w"
INC="-I$ROOT/src -I$ROOT/contrib/epee/include -I$ROOT/external/easylogging++ -I$ROOT/src/crypto/crypto_ops_builder/include -I$OUT/shim"

SOURCES_CPP="$ROOT/tests/conservation_oracle.cpp \
$ROOT/tests/conservation_oracle_probes.cpp \
$ROOT/tests/conservation_oracle_stubs.cpp \
$ROOT/src/ringct/rctOps.cpp $ROOT/src/ringct/rctTypes.cpp \
$ROOT/src/ringct/bulletproofs.cc $ROOT/src/ringct/bulletproofs_plus.cc \
$ROOT/src/ringct/multiexp.cc $ROOT/src/ringct/rctSigs.cpp \
$ROOT/src/device/device.cpp $ROOT/src/device/device_default.cpp $ROOT/src/device/log.cpp \
$ROOT/src/crypto/crypto.cpp $ROOT/src/crypto/hash.cpp $ROOT/src/crypto/hash.c $ROOT/src/crypto/slow-hash.c \
$ROOT/src/crypto/random.c $ROOT/src/crypto/CryptonightR_JIT.c \
$ROOT/src/crypto/tree-hash.c $ROOT/src/crypto/keccak.c $ROOT/src/crypto/hmac-keccak.c \
$ROOT/src/crypto/chacha.c $ROOT/src/crypto/blake2b.c $ROOT/src/crypto/aesb.c \
$ROOT/src/crypto/hash-extra-blake.c $ROOT/src/crypto/hash-extra-groestl.c \
$ROOT/src/crypto/hash-extra-jh.c $ROOT/src/crypto/hash-extra-skein.c \
$ROOT/src/crypto/blake256.c $ROOT/src/crypto/groestl.c $ROOT/src/crypto/jh.c \
$ROOT/src/crypto/skein.c $ROOT/src/crypto/oaes_lib.c \
$ROOT/src/crypto/crypto-ops.c $ROOT/src/crypto/crypto-ops-data.c \
$ROOT/src/crypto/generators.cpp \
$ROOT/src/cryptonote_basic/account.cpp $ROOT/src/cryptonote_basic/cryptonote_basic_impl.cpp \
$ROOT/src/cryptonote_basic/cryptonote_format_utils.cpp $ROOT/src/cryptonote_basic/cryptonote_format_utils_basic.cpp \
$ROOT/src/cryptonote_basic/difficulty.cpp \
$ROOT/src/common/perf_timer.cpp $ROOT/src/common/threadpool.cpp $ROOT/src/common/aligned.c \
$ROOT/src/common/base58.cpp \
$ROOT/contrib/epee/src/byte_slice.cpp $ROOT/contrib/epee/src/byte_stream.cpp \
$ROOT/contrib/epee/src/hex.cpp $ROOT/contrib/epee/src/mlocker.cpp $ROOT/contrib/epee/src/wipeable_string.cpp \
$ROOT/contrib/epee/src/memwipe.c $ROOT/contrib/epee/src/misc_language.cpp $ROOT/contrib/epee/src/int-util.cpp \
$ROOT/external/easylogging++/easylogging++.cc"

C_SOURCES="$ROOT/src/ringct/rctCryptoOps.c"
ASM_SOURCES="$ROOT/src/crypto/CryptonightR_template.S"

compile_one() {
  f="$1"
  case "$f" in
    *.c) o="$OUT/obj/$(echo "${f#"$ROOT"/}" | tr '/.' '__').o"; cmd="$CC $INC" ;;
    *.S) o="$OUT/obj/$(echo "${f#"$ROOT"/}" | tr '/.' '__').o"; cmd="gcc -c -O2 -w $INC" ;;
    *) o="$OUT/obj/$(echo "${f#"$ROOT"/}" | tr '/.' '__').o"; cmd="$CPP $INC" ;;
  esac
  case "$f" in
    *slow-hash.c) cmd="$cmd -maes" ;;
  esac
  if [ "$f" -nt "$o" ] || [ ! -f "$o" ]; then
    echo "[cc] $f"
    $cmd "$f" -o "$o"
  fi
}

for f in $SOURCES_CPP; do compile_one "$f"; done
for f in $C_SOURCES $ASM_SOURCES; do compile_one "$f"; done

# prefer a proper libsodium dev link if present, else the runtime soname
if [ -e /usr/lib/x86_64-linux-gnu/libsodium.so ] || [ -e /usr/local/lib/libsodium.so ]; then
  SODIUM="-lsodium"
else
  SODIUM="-l:libsodium.so.23"
fi

# shared objects = everything except the two mains (stubs must stay in)
CORE_OBJS=$(ls "$OUT"/obj/*.o | grep -vE "tests_conservation_oracle_(cpp|probes_cpp)\.o")

link_bin() {
  bin="$1"; mainobj="$2"
  echo "[link] $bin"
  g++ -O2 $CORE_OBJS "$mainobj" -o "$bin" \
    $SODIUM -lssl -lcrypto -lpthread -lboost_thread -lboost_chrono
}

link_bin "$OUT/conservation_oracle" "$OUT/obj/tests_conservation_oracle_cpp.o"
link_bin "$OUT/conservation_oracle_probes" "$OUT/obj/tests_conservation_oracle_probes_cpp.o"
echo "[done] $OUT/conservation_oracle, $OUT/conservation_oracle_probes"
